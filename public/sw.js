// Service worker do Sena NFC: deixa o app instalável e mostra um aviso quando estiver sem internet.
// Não guarda páginas do painel (sempre pega a versão nova do servidor).
const CACHE = "snfc-v1";
const OFFLINE = "/offline.html";
const ASSETS = [OFFLINE, "/icon-192.png", "/apple-touch-icon.png"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)));
  self.skipWaiting();
});

self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))));
  self.clients.claim();
});

self.addEventListener("fetch", (e) => {
  if (e.request.mode !== "navigate") return;
  e.respondWith(fetch(e.request).catch(() => caches.match(OFFLINE)));
});
